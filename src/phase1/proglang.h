#ifndef PHASE1_PROGLANG_H
#define PHASE1_PROGLANG_H

// ============================================================================
// 프로그래밍언어 패턴 (Phase 1)
// ----------------------------------------------------------------------------
// 컨셉: 콘솔 계산기(C++) 소스코드 한 줄씩이 화면 하단에서 위로 상승.
//       각 코드 라인은 '단어(토큰) 단위'로 발판이 됨.
//       플레이어는 단어 사이의 공백 구간으로만 통과 가능.
//       단어 블록을 밟으면 그 위에 착지하고, 화면 최상단(y=0)에 닿으면 피격.
// ----------------------------------------------------------------------------
// 외부 노출 API: phase1.c 디스패처가 호출.
//   - proglang_start    : 상태 초기화 (스폰 카운터 / 라인 배열 / 폰트 로드)
//   - proglang_update   : 시간 누적, 스폰 트리거, 라인 상승, 충돌/착지 처리
//   - proglang_draw     : 활성 라인들을 SDL2_ttf로 렌더링
//   - proglang_finished : 모든 라인 소진 + 화면에 남은 라인 없음 여부
// ============================================================================

#include <SDL.h>
#include <stdbool.h>

void proglang_start(void);
void proglang_update(float dt);
void proglang_draw(SDL_Renderer *r);
bool proglang_finished(void);

#endif
